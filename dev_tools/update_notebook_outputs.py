"""Execute the marimo notebooks and cache them as ``.ipynb`` for the docs.

Every notebook shown in the docs is a marimo ``.py`` file; that is the
source developers edit. nbsphinx needs an ``.ipynb`` with outputs, and
running the notebooks is slow (some run full simulations), so the executed
``.ipynb`` are cached in an ``autogenerated/`` folder next to each source::

    blond/examples/notebooks/getting_started.py                  <- edit
    blond/examples/notebooks/autogenerated/getting_started.ipynb <- generated

The cache is committed and the docs build only reads it; it never executes
a notebook. Refresh the cache after changing a notebook, or after a BLonD
change that should show up in the outputs, with either of::

    cd docs && bash create_docs.sh --rerun-notebooks
    python dev_tools/update_notebook_outputs.py [NOTEBOOK.py ...]

Without arguments, every notebook in ``NOTEBOOKS`` is executed. Each cached
``.ipynb`` records the SHA-256 of the source it was generated from, so the
docs build can name the notebooks whose cache is out of date.
"""

import hashlib
import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CACHE_DIR_NAME = "autogenerated"
SOURCE_HASH_KEY = "blond_marimo_source_sha256"

# marimo notebook (relative to the repo root) -> hide_code: if True, the
# docs page shows only the cell outputs, not the code that produced them.
NOTEBOOKS = {
    "blond/examples/notebooks/getting_started.py": False,
    "blond/examples/notebooks/single_bunch_acceleration.py": False,
    "blond/examples/notebooks/tutorial_SemiEmpiricMatcher.py": False,
    "blond/examples/notebooks/wake_impedance_pooled.py": False,
    "docs/models_new/pole-residue/bin_averaged_wake_derivation.py": True,
    "docs/models_new/pole-residue/explain_nearfield_farfield_model.py": False,
}

# Shown at the top of every cached .ipynb opened in Jupyter. nbsphinx drops
# raw cells of a mimetype it does not render, so the docs pages omit it.
RERUN_HINT = (
    "AUTOGENERATED, DO NOT EDIT: executed copy of the marimo notebook "
    "{source}. Edit that file instead, then refresh this cache with "
    "`cd docs && bash create_docs.sh --rerun-notebooks` (all notebooks) or "
    "`python dev_tools/update_notebook_outputs.py {source}` (just this one)."
)

# Hides the code cells of a notebook page; outputs and their layout stay.
HIDE_CODE_STYLE = (
    "<style>div.nbinput.container { display: none; }\n"
    "div.nboutput.container div.prompt { display: none; }</style>"
)


def cache_path(notebook: Path) -> Path:
    """
    Return where the executed ``.ipynb`` of a notebook is cached.

    Parameters
    ----------
    notebook
        Path of the marimo ``.py`` notebook.

    Returns
    -------
    cached_notebook
        ``<notebook dir>/autogenerated/<notebook name>.ipynb``.
    """
    return notebook.parent / CACHE_DIR_NAME / f"{notebook.stem}.ipynb"


def source_hash(notebook: Path) -> str:
    """
    Return the SHA-256 hex digest of a notebook source.

    Parameters
    ----------
    notebook
        Path of the marimo ``.py`` notebook.

    Returns
    -------
    digest
        Hex digest of the file contents.
    """
    return hashlib.sha256(notebook.read_bytes()).hexdigest()


def convert_marimo_math(text: str, target: Path) -> str:
    r"""
    Rewrite marimo's math tags to delimiters MathJax renders.

    marimo wraps math as ``<marimo-tex>||[ ... ||]</marimo-tex>``, which
    only its own frontend renders, so the tags are rewritten to
    ``\[ ... \]`` / ``\( ... \)``.

    Parameters
    ----------
    text
        JSON text of the exported ``.ipynb``.
    target
        Path of the exported ``.ipynb``, for the error message.

    Returns
    -------
    converted_text
        ``text`` with every ``<marimo-tex>`` tag rewritten.

    Raises
    ------
    RuntimeError
        If a ``<marimo-tex>`` tag survives the rewrite, i.e. marimo
        changed its output format.
    """
    text = re.sub(
        r'<marimo-tex class=\\"arithmatex\\">\|\|([\[(])(.*?)'
        r"\|\|[\])]</marimo-tex>",
        lambda m: rf"\\{m[1]}{m[2]}\\{']' if m[1] == '[' else ')'}",
        text,
    )
    if "marimo-tex" in text:
        raise RuntimeError(
            f"Unconverted <marimo-tex> left in {target}; marimo changed "
            "its math output, update convert_marimo_math."
        )
    return text


def add_rerun_hint(exported: dict, notebook: Path) -> None:
    """
    Insert the "autogenerated, how to refresh" hint into an ``.ipynb``.

    Parameters
    ----------
    exported
        Parsed ``.ipynb``, modified in place. A hint already present is
        replaced, so calling this twice leaves a single hint.
    notebook
        Path of the marimo ``.py`` notebook it was generated from.
    """
    source = notebook.resolve().relative_to(ROOT).as_posix()
    hint = RERUN_HINT.format(source=source)
    exported["metadata"]["blond_autogenerated"] = hint
    exported["cells"] = [
        cell
        for cell in exported["cells"]
        if not cell["metadata"].get("blond_rerun_hint")
    ]
    exported["cells"].insert(
        0,
        {
            "cell_type": "raw",
            "metadata": {
                "raw_mimetype": "text/plain",
                "blond_rerun_hint": True,
            },
            "source": hint,
        },
    )


def export_notebook(notebook: Path, hide_code: bool) -> None:
    """
    Execute a marimo notebook and cache it as ``.ipynb`` with outputs.

    Parameters
    ----------
    notebook
        Path of the marimo ``.py`` notebook.
    hide_code
        If True, the docs page shows only the cell outputs.
    """
    target = cache_path(notebook)
    target.parent.mkdir(exist_ok=True)
    environment = dict(os.environ, MPLBACKEND="Agg")
    subprocess.run(
        [sys.executable, "-m", "marimo", "export", "ipynb", str(notebook),
         "-o", str(target), "--include-outputs", "--force"],
        check=True,
        env=environment,
    )  # fmt: skip
    text = convert_marimo_math(target.read_text(encoding="utf-8"), target)
    exported = json.loads(text)
    exported["metadata"][SOURCE_HASH_KEY] = source_hash(notebook)
    if hide_code:
        # nbsphinx can only hide whole cells (output included), so the
        # code is hidden with page-local CSS instead
        exported["cells"].insert(
            0,
            {
                "cell_type": "raw",
                "metadata": {"raw_mimetype": "text/html"},
                "source": HIDE_CODE_STYLE,
            },
        )
    add_rerun_hint(exported, notebook)
    target.write_text(
        json.dumps(exported, indent=1, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )


def check_cache() -> list[str]:
    """
    Check that every notebook has a cached ``.ipynb`` from its source.

    Returns
    -------
    stale
        Notebooks (relative to the repo root) whose cache was generated
        from a different version of the source.

    Raises
    ------
    FileNotFoundError
        If a notebook has no cached ``.ipynb`` at all.
    """
    stale = []
    for name in NOTEBOOKS:
        notebook = ROOT / name
        target = cache_path(notebook)
        if not target.exists():
            raise FileNotFoundError(
                f"{target.relative_to(ROOT)} is missing. Generate it with "
                f"`python dev_tools/update_notebook_outputs.py {name}`."
            )
        metadata = json.loads(target.read_text(encoding="utf-8"))["metadata"]
        if metadata.get(SOURCE_HASH_KEY) != source_hash(notebook):
            stale.append(name)
    return stale


def main(notebooks: list[str]) -> None:
    """
    Export the given notebooks, or all notebooks in ``NOTEBOOKS``.

    Parameters
    ----------
    notebooks
        Paths of marimo notebooks, each listed in ``NOTEBOOKS``. Empty
        means all of them.

    Raises
    ------
    ValueError
        If a notebook is not listed in ``NOTEBOOKS``.
    """
    names = [
        Path(notebook).resolve().relative_to(ROOT).as_posix()
        for notebook in notebooks
    ] or list(NOTEBOOKS)
    unknown = [name for name in names if name not in NOTEBOOKS]
    if unknown:
        raise ValueError(
            f"Not listed in NOTEBOOKS of {Path(__file__).name}: {unknown}"
        )
    for name in names:
        print(f"Executing {name}", flush=True)
        export_notebook(ROOT / name, NOTEBOOKS[name])


if __name__ == "__main__":
    main(sys.argv[1:])
