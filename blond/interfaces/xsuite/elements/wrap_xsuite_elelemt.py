"""
Wrap any xsuite element / line as a single black-box BLonD ring element.

The wrapper transports particles between BLonD's ``(dt, dE)`` and xsuite's
``(zeta, ptau)`` coordinates, runs the xsuite element's ``track``, and
tells the BLonD ring how long it is and how much reference time it
consumes — *nothing else*. It deliberately does not introspect what kind
of element it wraps. From BLonD's analytics' point of view (``phi_s``,
slip-factor averaging, voltage sums) the xsuite block is invisible.

This is the black-box treatment we want: xsuite owns its physics, BLonD
owns its loop, the wrapper is purely transport. If a user needs BLonD
to compute things that depend on the lattice (``phi_s``, eta_0
averaging), they add parallel BLonD elements with matching parameters
alongside the wrapper.
"""

from __future__ import annotations

import math
from typing import TYPE_CHECKING, Any

import numpy as np

from blond.core.beam.flags import BeamFlags
from blond.interfaces.xsuite.elements.helpers import (
    ReferenceFrame,
    dE_to_ptau,
    dt_to_zeta,
    ptau_to_dE,
    zeta_to_dt,
)
from blond.physics.cavities import RFStationBaseClass
from blond.physics.drifts import DriftBaseClass

if TYPE_CHECKING:  # pragma: no cover
    from xtrack import BeamElement, Line, Particles

    from blond.core.beam.base import BeamBaseClass
    from blond.core.reference_clock.reference_clock import ReferenceCoordinates
    from blond.core.simulation.simulation import Simulation

    # Any xsuite guest the wrapper accepts: a single beam element (Drift,
    # Cavity, Multipole, ReferenceEnergyIncrease, … — all subclass
    # ``BeamElement``) or a full ``Line``. Both expose ``track(particles)``.
    XsuiteTrackable = BeamElement | Line


def _to_numpy(array) -> np.ndarray:
    """
    Return a host numpy view of ``array``, copying off-GPU if needed.

    BLonD's ``beam.*.array_local`` storage is cupy when the backend is GPU;
    xsuite ``Particles`` in this wrapper are always numpy. ``.get()`` pulls a
    cupy array back to host; plain numpy / array-likes pass through
    ``np.asarray`` unchanged.

    Parameters
    ----------
    array
        A cupy array, numpy array or array-like.

    Returns
    -------
    numpy.ndarray
        A host numpy array.
    """
    if hasattr(array, "get"):
        return array.get()
    return np.asarray(array)


def _extract_length(element: XsuiteTrackable) -> float:
    r"""
    Return a finite drift length for an xsuite guest, or raise ``TypeError``.

    Works for single elements with ``.length`` (``xt.Drift``,
    ``xt.LineSegmentMap``, …) and for full ``xt.Line``\s via
    ``get_length()``. Raises for guests with no defined length (markers,
    apertures) — pass ``orbit_length=`` explicitly in that case.

    Parameters
    ----------
    element
        An xsuite element or line to measure.

    Returns
    -------
    float
        The orbit length [m].
    """
    length = getattr(element, "length", None)
    if length is not None:
        try:
            return float(length)
        except TypeError:
            return float(_to_numpy(length).item())
    if hasattr(element, "get_length"):
        return float(element.get_length())
    raise TypeError(
        f"Cannot determine an orbit length for xsuite guest "
        f"{type(element).__name__}; pass `orbit_length=` explicitly "
        f"(use 0.0 for markers / apertures with no spatial extent)."
    )


